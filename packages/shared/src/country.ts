const COUNTRY_CODE_SET = new Set(COUNTRIES.map((c) => c.code));

export function isValidCountryCode(code?: string | null): boolean {
  if (!code || typeof code !== 'string') return false;
  return COUNTRY_CODE_SET.has(code.trim().toUpperCase());
}

export function getCountryByCode(code?: string | null): Country | undefined {
  if (!code || typeof code !== 'string') return undefined;
  const upper = code.trim().toUpperCase();
  return COUNTRIES.find((c) => c.code === upper);
}

/**
 * Checks whether an IP address is a private, loopback, or link-local address.
 */
export function isPrivateIp(ip: string): boolean {
  if (!ip) return true;
  const cleaned = cleanIp(ip);
  if (!cleaned || cleaned === '127.0.0.1' || cleaned === '::1' || cleaned === 'localhost') return true;

  // IPv4 Private ranges
  if (/^10\./.test(cleaned)) return true;
  if (/^192\.168\./.test(cleaned)) return true;
  if (/^172\.(1[6-9]|2[0-9]|3[0-1])\./.test(cleaned)) return true;
  if (/^169\.254\./.test(cleaned)) return true; // Link-local

  // IPv6 ULA and link-local
  if (/^(fc00|fd00|fe80)/i.test(cleaned)) return true;

  return false;
}

/**
 * Extract country code from incoming edge CDN / proxy headers or browser Accept-Language.
 */
export function detectCountryFromHeaders(headers: Record<string, any>): string | null {
  if (!headers) return null;

  // 1. Edge & Proxy Geolocation Headers
  const edgeHeaders = [
    'cf-ipcountry',
    'x-country-code',
    'x-geo-country',
    'cloudfront-viewer-country',
    'x-vercel-ip-country',
    'geoip-country-code',
  ];

  for (const h of edgeHeaders) {
    const val = headers[h];
    if (typeof val === 'string') {
      const code = val.trim().toUpperCase();
      if (code && code !== 'XX' && code !== 'T1' && isValidCountryCode(code)) {
        return code;
      }
    }
  }

  // 2. Browser Accept-Language Region Subtag (e.g. "en-US,en;q=0.9", "en-NG", "fr-FR")
  const acceptLang = headers['accept-language'];
  if (typeof acceptLang === 'string' && acceptLang.trim()) {
    const tokens = acceptLang.split(',');
    for (const token of tokens) {
      const tag = token.split(';')[0].trim();
      const parts = tag.split(/[-_]/);
      if (parts.length >= 2) {
        const candidate = parts[1].trim().toUpperCase();
        if (candidate.length === 2 && isValidCountryCode(candidate)) {
          return candidate;
        }
      }
    }
  }

  return null;
}

/**
 * Query external fast IP geolocation for public IPs with a strict 1500ms timeout.
 */
export async function detectCountryFromIp(ip?: string | null): Promise<string | null> {
  if (!ip) return null;
  const cleaned = cleanIp(ip);
  if (isPrivateIp(cleaned)) return null;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 1500);

  try {
    const res = await fetch(`http://ip-api.com/json/${cleaned}?fields=countryCode`, {
      signal: controller.signal,
    });
    if (!res.ok) return null;
    const body = (await res.json()) as { countryCode?: string };
    if (body.countryCode && isValidCountryCode(body.countryCode)) {
      return body.countryCode.toUpperCase();
    }
  } catch {
    // Non-blocking fallback
  } finally {
    clearTimeout(timer);
  }

  return null;
}

/**
 * Detect user country code asynchronously (checks headers, public IP geo, Accept-Language, fallback).
 * Perfect for account creation (/register) where an async request is handled.
 */
export async function detectCountry(req: { headers: Record<string, any>; ip?: string }): Promise<string> {
  // 1. Direct edge headers (Cloudflare, CloudFront, Vercel)
  const headerCountry = detectCountryFromHeaders(req.headers);
  if (headerCountry) return headerCountry;

  // 2. Public IP resolution if not local
  const ip = getClientIp(req);
  if (ip && !isPrivateIp(ip)) {
    const ipCountry = await detectCountryFromIp(ip);
    if (ipCountry) return ipCountry;
  }

  return 'US';
}

/**
 * Synchronous version for HTML page templates (no latency).
 */
export function detectCountrySync(req: { headers: Record<string, any>; ip?: string }): string {
  const code = detectCountryFromHeaders(req.headers);
  return code || 'US';
}
